def _ts(days_ago: int = 0) -> str:
    d = datetime.now(timezone.utc) - timedelta(days=days_ago)
    return d.isoformat(timespec="seconds").replace("+00:00", "Z")


def _future(days: int) -> str:
    d = datetime.now(timezone.utc) + timedelta(days=days)
    return d.isoformat(timespec="seconds").replace("+00:00", "Z")


